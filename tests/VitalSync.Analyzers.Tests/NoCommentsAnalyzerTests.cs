using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace VitalSync.Analyzers.Tests;

public sealed class NoCommentsAnalyzerTests
{
    [Theory]
    [InlineData("class C { int x; // note\n}")]
    [InlineData("class C { /* note */ int x; }")]
    [InlineData("/// <summary>Note</summary>\nclass C { }")]
    [InlineData("/** <summary>Note</summary> */\nclass C { }")]
    public async Task Reports_every_kind_of_csharp_comment(string source)
    {
        var diagnostics = await AnalyzeAsync(source);

        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal(NoCommentsAnalyzer.DiagnosticId, diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
    }

    [Fact]
    public async Task Ignores_comment_markers_inside_strings()
    {
        var diagnostics = await AnalyzeAsync("class C { string a = \"https://example.org\"; string b = \"/* */\"; }");

        Assert.Empty(diagnostics);
    }

    [Fact]
    public async Task Skips_generated_code()
    {
        var diagnostics = await AnalyzeAsync("// <auto-generated />\nclass C { /// <inheritdoc />\n void M() { } }");

        Assert.Empty(diagnostics);
    }

    [Fact]
    public async Task Reports_a_comment_that_generated_code_maps_back_to_a_razor_file()
    {
        const string source = """
            // <auto-generated />
            class C
            {
            #line 12 "Pages/Home.razor"
                // written in the component
                void M() { }
            #line default
            #line hidden
                // written by the generator
            }
            """;

        var diagnostics = await AnalyzeAsync(source);

        var diagnostic = Assert.Single(diagnostics);
        var mapped = diagnostic.Location.GetMappedLineSpan();
        Assert.Equal("Pages/Home.razor", mapped.Path);
        Assert.Equal(11, mapped.StartLinePosition.Line);
    }

    [Theory]
    [InlineData("Button.razor.css", ".button {\n  /* note */\n  color: red;\n}", 1)]
    [InlineData("Button.razor", "<p>Ok</p>\n@* note *@", 1)]
    [InlineData("Button.razor", "<!-- note -->\n<button>Ok</button>", 0)]
    [InlineData("Table.razor.js", "export function f() {\n  return 1; // note\n}", 1)]
    [InlineData("theme.js", "/* note */\nexport const a = 1;", 0)]
    public async Task Reports_comments_in_razor_css_and_javascript(string path, string text, int line)
    {
        var diagnostics = await AnalyzeAsync("class C { }", new InMemoryAdditionalText(path, text));

        var span = Assert.Single(diagnostics).Location.GetLineSpan();
        Assert.Equal(path, span.Path);
        Assert.Equal(line, span.StartLinePosition.Line);
    }

    [Theory]
    [InlineData("Button.razor.css", ".button::before { content: \"/* */\"; }")]
    [InlineData("Button.razor", "<a href=\"mailto:a@b.ch\">@@*</a>")]
    [InlineData("Table.razor.js", "export const url = `https://${host}/${'//'}`;")]
    [InlineData("rules.json", "{ // note\n}")]
    public async Task Ignores_markers_that_are_not_comments_and_files_left_to_the_repository_test(string path, string text)
    {
        var diagnostics = await AnalyzeAsync("class C { }", new InMemoryAdditionalText(path, text));

        Assert.Empty(diagnostics);
    }

    private static async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(string source, params AdditionalText[] additionalFiles)
    {
        var compilation = CSharpCompilation.Create(
            "Analyzed",
            [CSharpSyntaxTree.ParseText(source, path: "Source.cs", cancellationToken: TestContext.Current.CancellationToken)],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var analyzed = compilation.WithAnalyzers(
            [new NoCommentsAnalyzer()],
            new AnalyzerOptions([.. additionalFiles]));

        return await analyzed.GetAnalyzerDiagnosticsAsync(TestContext.Current.CancellationToken);
    }

    private sealed class InMemoryAdditionalText(string path, string text) : AdditionalText
    {
        public override string Path { get; } = path;

        public override SourceText GetText(CancellationToken cancellationToken = default) => SourceText.From(text);
    }
}
